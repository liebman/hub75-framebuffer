#[cfg(feature = "tail-closes-latch")]
pub(crate) use crate::pinmap::ADDR_MASK;
pub(crate) use crate::pinmap::PINMAP;
pub(crate) use crate::pinmap::{
    ADDR_SHIFT, COLOR0_MASK, COLOR0_SHIFT, COLOR1_MASK, COLOR1_SHIFT, COLOR_MASK, LATCH_BIT, OE_BIT,
};
pub(crate) use crate::{INTER_ROW_BLANK, LEAD_BLANK_DELAY, TRAIL_BLANK_DELAY};

// The OE *level* constants stay local: their default polarity differs between
// this module (standard active-low) and the deprecated `plain` module
// (active-high). Only the bit position (`pinmap::OE_BIT`) is shared.
#[cfg(feature = "invert-oe")]
pub(crate) const OE_ACTIVE: u16 = OE_BIT;
#[cfg(feature = "invert-oe")]
pub(crate) const OE_BLANK: u16 = 0;

#[cfg(not(feature = "invert-oe"))]
pub(crate) const OE_ACTIVE: u16 = 0;
#[cfg(not(feature = "invert-oe"))]
pub(crate) const OE_BLANK: u16 = OE_BIT;

// ---------------------------------------------------------------------------
// Shared helper functions
// ---------------------------------------------------------------------------

#[inline]
pub(crate) const fn map_index(i: usize) -> usize {
    #[cfg(feature = "esp32-ordering")]
    {
        i ^ 1
    }
    #[cfg(not(feature = "esp32-ordering"))]
    {
        i
    }
}

/// Builds the per-row pixel template with trail blank, active pixels, lead
/// blank, and latch embedded within the COLS entries.
#[allow(clippy::absurd_extreme_comparisons)]
#[inline]
pub(crate) const fn make_data_template<const COLS: usize>(addr: u8) -> [Entry; COLS] {
    let mut data = [Entry::new(); COLS];
    let mut i = 0;

    while i < COLS {
        let mut entry = Entry::new();
        entry.0 = ((addr as u16) << ADDR_SHIFT) | OE_BLANK;

        if i == COLS - 1 {
            entry.0 |= LATCH_BIT;
        } else if i >= TRAIL_BLANK_DELAY && i < COLS.saturating_sub(LEAD_BLANK_DELAY + 1) {
            entry.0 = (entry.0 & !OE_BIT) | OE_ACTIVE;
        }

        data[map_index(i)] = entry;
        i += 1;
    }

    data
}

// ---------------------------------------------------------------------------
// Entry — the 16-bit word that rides on the HUB75 bus
// ---------------------------------------------------------------------------

// The bit layout is selected per board by `crate::pinmap`; this single
// `bitfield!` definition reads the positions straight from `PINMAP` so the
// accessors can never drift out of sync with the DMA templates. Note the
// `red1/grn1/blu1` accessors are the *upper-half* triplet (`PINMAP.red0`...),
// and `red2/grn2/blu2` the lower half.
bitfield! {
    #[derive(Clone, Copy, Default, PartialEq)]
    #[repr(transparent)]
    pub(crate) struct Entry(u16);
    pub(crate) dummy2, set_dummy2: PINMAP.spare[2];
    pub(crate) blu2, set_blu2: PINMAP.blu1;
    pub(crate) grn2, set_grn2: PINMAP.grn1;
    pub(crate) red2, set_red2: PINMAP.red1;
    pub(crate) blu1, set_blu1: PINMAP.blu0;
    pub(crate) grn1, set_grn1: PINMAP.grn0;
    pub(crate) red1, set_red1: PINMAP.red0;
    pub(crate) output_enable, set_output_enable: PINMAP.oe;
    pub(crate) dummy1, set_dummy1: PINMAP.spare[1];
    pub(crate) dummy0, set_dummy0: PINMAP.spare[0];
    pub(crate) latch, set_latch: PINMAP.latch;
    pub(crate) addr, set_addr: PINMAP.addr_msb(), PINMAP.addr_lsb;
}

impl core::fmt::Debug for Entry {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_tuple("Entry")
            .field(&format_args!("{:#x}", self.0))
            .finish()
    }
}

impl Entry {
    pub(crate) const fn new() -> Self {
        Self(OE_BLANK)
    }

    pub(crate) const fn from_raw(val: u16) -> Self {
        Self(val)
    }

    #[allow(dead_code)]
    pub(crate) const fn raw(self) -> u16 {
        self.0
    }

    pub(crate) fn mask_raw(&mut self, mask: u16) {
        self.0 &= mask;
    }

    // The colour bit positions/masks come from `crate::pinmap` so they follow
    // the selected board layout.
    #[inline]
    pub(crate) fn set_color0_bits(&mut self, bits: u8) {
        let bits16 = u16::from(bits) << COLOR0_SHIFT;
        self.0 = (self.0 & !COLOR0_MASK) | (bits16 & COLOR0_MASK);
    }

    #[inline]
    pub(crate) fn set_color1_bits(&mut self, bits: u8) {
        let bits16 = u16::from(bits) << COLOR1_SHIFT;
        self.0 = (self.0 & !COLOR1_MASK) | (bits16 & COLOR1_MASK);
    }
}
